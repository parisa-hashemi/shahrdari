function chapters(defs: [string, StudyChapter['status'], string, number, number][]): StudyChapter[] {
  return defs.map(([title, status, owner, required, bound], index) => ({
    key: `ch-${index}`,
    index,
    title,
    status,
    ownerName: owner,
    requiredInputs: required,
    boundInputs: bound,
  }));
}

